def _pre(text):
    return (f"<pre style='margin:0;background:#1e293b;color:#e2e8f0;border-radius:8px;padding:8px 12px;"
            f"font-size:.8rem;line-height:1.55;font-family:Consolas,Menlo,monospace;white-space:pre-wrap;'>{_h.escape(text)}</pre>")


def samples(rows):
    """範例輸入／輸出表格。rows: [(輸入, 輸出)]"""
    body = ''.join(f"<tr><td style='padding:6px;vertical-align:top;'>{_pre(i)}</td>"
                   f"<td style='padding:6px;vertical-align:top;'>{_pre(o)}</td></tr>" for i, o in rows)
    return (f"<table style='width:100%;border-collapse:collapse;margin-bottom:10px;'>"
            f"<tr><th style='text-align:left;font-size:.78rem;color:#475569;padding:0 6px;'>範例輸入</th>"
            f"<th style='text-align:left;font-size:.78rem;color:#475569;padding:0 6px;'>範例輸出</th></tr>{body}</table>")


